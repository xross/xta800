DecoderGenerator::DecoderGenerator(const char *fileName, DbInterface &dbInterface, 
                                   XmosUtils *xmosUtils, const char *version) :
  m_dbInterface(dbInterface),
  m_xmosUtils(xmosUtils),
  m_version(version)
{
  FILE *outFp = fopen(fileName, "w");
  if (outFp == NULL)
  {
    fprintf(stderr, "ERROR: Unable to open file %s for reading!\n", fileName);
    exit(1);
  }

  setIndent(1);

  generateHeader(outFp);

  fprintf(outFp, "package com.xmos.xta.core.engine.instructions;\n");
  fprintf(outFp, "\n");
  fprintf(outFp, "import com.xmos.libs.isa.Instruction;\n");
  fprintf(outFp, "\n");
  fprintf(outFp, "public class %sXtaInstructionDecoder extends XtaInstructionDecoder {\n", m_version);
  fprintf(outFp, "    public XtaInstruction decode(int opcode, long pc) {\n");

  DecodeNode *root = dbInterface.getDecodeTree();

  generateTree(outFp, root, true);

  fprintf(outFp, "        return new NullInstruction(\"...\", opcode, pc, 2, false);\n");
  fprintf(outFp, "    }\n");
  fprintf(outFp, "}\n");

  fclose(outFp);
}

DecoderGenerator::~DecoderGenerator()
{
  m_xmosUtils = 0;
}

void DecoderGenerator::generateHeader(FILE *outFp)
{
  fprintf(outFp, "/*\n");
  fprintf(outFp, " *\n");
  fprintf(outFp, " * Copyright XMOS Limited - (c) 2005, 2006\n");
  fprintf(outFp, " *\n");
  fprintf(outFp, " * AUTOGENERATED - DO NOT EDIT\n");;
  fprintf(outFp, " *\n");
  fprintf(outFp, " */\n");
  fprintf(outFp, "\n");
}

void DecoderGenerator::generateTree(FILE *outFp, DecodeNode *node, bool isStart)
{
  if (node->isTerminal())
  {
    fprintf(outFp, ") {\n");
    printNode(outFp, node);
    printIndent(outFp);
    fprintf(outFp, "}\n");
  }
  else
  {
    uint numNodes = node->numNodes();
    if (numNodes == 1)
    {
      DecodeNode *subNode = node->getNode(0);
      fprintf(outFp, " && \n");
      printIndent(outFp);
      fprintf(outFp, "    ");
      printNodeDecision(outFp, node, subNode);

      generateTree(outFp, subNode, false);
    }
    else
    {
      if (isStart == false)
        fprintf(outFp, ") {\n");

      incIndent();

      for (uint nodeNum = 0; nodeNum < numNodes; nodeNum++)
      {
        DecodeNode *subNode = node->getNode(nodeNum);
        printIndent(outFp);

        // For those that aren't the first element, need the else
        if (nodeNum != 0)
          fprintf(outFp, "else ");

        fprintf(outFp, "if (");
        printNodeDecision(outFp, node, subNode);

        generateTree(outFp, subNode, false);
      }

      decIndent();
      if (isStart == false)
      {
        printIndent(outFp);
        fprintf(outFp, "}\n");
      }
    }
  }
}

void DecoderGenerator::printNode(FILE *outFp, DecodeNode *node)
{
  DbInstruction *inst = node->getInstruction();
  DbFormat      *fmt  = node->getFormat();

  const string *instName = inst->getLowerName();
  const string *fmtName  = fmt->getName();
  string className = *instName + "_" + *fmtName;

  printIndent(outFp);
  fprintf(outFp, "  XtaInstruction instruction =  new %sXtaInstruction_%s(opcode, pc);\n", 
    m_version, className.c_str());

  calculateBranchTargetInfo(outFp, fmt, inst);

  printIndent(outFp);
  fprintf(outFp, "  return instruction;\n");
}

void DecoderGenerator::printNodeDecision(FILE *outFp, DecodeNode *node, DecodeNode *subNode)
{
  uint minimum = subNode->getMin();
  uint maximum = subNode->getMax();

  if (subNode->isRange())
  {
    fprintf(outFp, "(");
    printField(outFp, node);
    fprintf(outFp, " >= ");
    fprintf(outFp, "%d", minimum);
    fprintf(outFp, ")");
    fprintf(outFp, " && ");
    fprintf(outFp, "(");
    printField(outFp, node);
    fprintf(outFp, " <= ");
    fprintf(outFp, "%d", maximum);
    fprintf(outFp, ")");
  }
  else
  {
    fprintf(outFp, "(");
    printField(outFp, node);
    fprintf(outFp, " == ");
    fprintf(outFp, "%d", minimum);
    fprintf(outFp, ")");
  }
}

void DecoderGenerator::printField(FILE *outFp, DecodeNode *node)
{
  uint size   = node->getFieldSize();
  uint offset = node->getFieldOffset();

  fprintf(outFp, "((opcode >> ");
  fprintf(outFp, "%d", offset);
  fprintf(outFp, ") & ((1 << ");
  fprintf(outFp, "%d", size);
  fprintf(outFp, ") - 1))");
}

void DecoderGenerator::printIndent(FILE *outFp)
{
  for (int i = 0; i < m_indent; i++)
    fprintf(outFp, "    ");
}

void DecoderGenerator::setIndent(int indent)
{
  m_indent = indent;
}

void DecoderGenerator::incIndent()
{
  m_indent++;
}

void DecoderGenerator::decIndent()
{
  ASSERT(m_indent > 0);

  m_indent--;
}

void DecoderGenerator::calculateBranchTargetInfo(FILE *outFp, DbFormat *fmt, DbInstruction *inst)
{
  if (inst->isPcRel())
  {
    DbOperand *branchTargetOperand = NULL;
    for (int operIndex = 0; operIndex < fmt->numOperands(); ++operIndex)
    {
      DbOperand *operand = fmt->getOperand(operIndex);
      if (*operand->getRelocationType() != "R_XCORE1_NONE")
      {
        branchTargetOperand = operand;
        break;
      }
    }
    if (branchTargetOperand != NULL)
    {
      ASSERT(branchTargetOperand->isImm());
      const string *scale = preProcess(branchTargetOperand->getScale());

      printIndent(outFp);
      fprintf(outFp, "  instruction.setBranchPcRelative(true);\n");
      printIndent(outFp);

     string *branchDecodeString = preProcess(branchTargetOperand->getField()->getDecode());
      if (branchTargetOperand->isInverted())
      {
        fprintf(outFp, "  instruction.setBranchPcRelativeTargetPc(pc + %d - (%s << %s));\n", 
          fmt->numBytes(), branchDecodeString->c_str(), scale->c_str());
      }
      else
      {
        fprintf(outFp, "  instruction.setBranchPcRelativeTargetPc(pc + %d + (%s << %s));\n", 
          fmt->numBytes(), branchDecodeString->c_str(), scale->c_str());
      }
    }
  }
}

string *DecoderGenerator::preProcess(const string *txt)
{
  StringVector *tokens = m_xmosUtils->stringLibrary->strTok(txt, "", TOKENISERS);
  bool skipComma = false;

  string newTxt;
  StringVector::const_iterator iter;
  for (iter = tokens->begin(); iter != tokens->end(); ++iter)
  {
    const string *token = *iter;
    if (skipComma)
    {
      skipComma = false;
      if (*token != ",")
        newTxt = newTxt + *token;
      continue;
    }

    if (*token == "getBits") {
      newTxt = newTxt + "Instruction.getBits";
    } else if (*token == "getBitsHL") {
      newTxt = newTxt + "Instruction.getBitsHL";
    } else if (*token == "ISSUE_MODE_MIN_INSTR_PKT_SIZE") {
      // TODO: cope with issue mode 
      newTxt = newTxt + "1";
    } else {
      newTxt = newTxt + *token;
    }

  }
  m_xmosUtils->stringLibrary->deleteStr(tokens);

  return SAFE_NEW(string(newTxt.begin(), newTxt.end()));
}

#ifndef COPROCESSOR_H_
#define COPROCESSOR_H_

#include <xccompat.h>
#include "coProcessor_registers.h"

/*
 * Apple Authentication Coprocessor Functions
 * Ref 2.0B Specification
 */

// ---------------------------------------------------------------

/* 
 * coProcessorInit
 * Verify coprocessor device version
 */
int coProcessorInit();

/* 
 * coProcessorBusy
 * Checks if coProcessor is still running previous command
 */
int coProcessorBusy();

/*
 * coProcessorValidResults
 * Check if previous command was successful
 */
int coProcessorValidResults();


/*
 * ---------- CoProcessor commands ----------
 */

/*
 * coProcessorStartSigGeneration
 * Start signature generation from a iPod challenge
 */
int coProcessorStartSigGeneration();

/*
 * coProcessorStartSigVerification
 * Start validating an iPod's response
 */
int coProcessorStartSigVerification();

/*
 * coProcessorGenerateChallenge
 * Generate a challenge for the iPod
 */
int coProcessorGenerateChallenge();


/*
 * coProcessorStartCertValidation
 * Validate iPod's certificate
 */
int coProcessorStartCertValidation();


/*
 * ---------- CoProcessor data retrieval ----------
 */

#if defined __XC__
int coProcessorGetAuthVersion(char &major, char &minor);
#elif defined __STDC__
int coProcessorGetAuthVersion(char *major, char *minor);
#endif


/*
 * coProcessorGetDeviceID
 * Retrieve Device ID of Coprocessor
 */
#if defined __XC__
int coProcessorGetDeviceID(int &retVal);
#elif defined __STDC__
int coProcessorGetDeviceID(int *retVal);
#endif

/*
 * coProcessorGetAccessoryCertificate
 * Retrieve Accessory Certificate stored in coProcessor flash
 */
#if defined __XC__
int coProcessorGetAccessoryCertificate(unsigned short &len, unsigned char data[]);
#elif defined __STDC__
int coProcessorGetAccessoryCertificate(unsigned short *len, unsigned char *data);
#endif

/*
 * coProcessorGetSignature
 * Retrieve signature generated from challenge
 */
#if defined __XC__
int coProcessorGetSignature(unsigned &len, unsigned char data[]);
#elif defined __STDC__
int coProcessorGetSignature(unsigned *len, unsigned char *data);
#endif

/*
 * coProcessorGetChallenge
 * Retrieve challenge generated by coProcessor
 */
#if defined __XC__
int coProcessorGetChallenge(unsigned short &len, unsigned char data[]);
#elif defined __STDC__
int coProcessorGetChallenge(unsigned short *len, unsigned char *data);
#endif

/*
 * ---------- CoProcessor data storing ----------
 */

/*
 * coProcessorPutChallenge
 * Store challenge generated by iPod
 */
#if defined __XC__
int coProcessorPutChallenge(unsigned short len, unsigned char data[]);
#elif defined __STDC__
int coProcessorPutChallenge(unsigned short len, unsigned char *data);
#endif

/*
 * coProcessorPutSignature
 * Store signature generated by iPod
 */
#if defined __XC__
int coProcessorPutSignature(unsigned short len, unsigned char data[]);
#elif defined __STDC__
int coProcessorPutSignature(unsigned short len, unsigned char *data);
#endif

/*
 * coProcessorPutiPodCert
 * Store iPod's certificate for verification
 */
#if defined __XC__
int coProcessorPutiPodCert(unsigned short len, unsigned char data[]);
#elif defined __STDC__
int coProcessorPutiPodCert(unsigned short len, unsigned char *data);
#endif

#endif /*COPROCESSOR_H_*/

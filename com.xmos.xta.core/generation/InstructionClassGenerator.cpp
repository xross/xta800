InstructionClassGenerator::InstructionClassGenerator(const char *fileName, DbInterface &dbInterface, 
                                                     XmosUtils *xmosUtils, const char *version) :
  m_xmosUtils(xmosUtils),
  m_outFile(fileName),
  m_dbInterface(dbInterface),
  m_version(version)
{
  generateHeader();
  generateDefinitions();
}

InstructionClassGenerator::~InstructionClassGenerator()
{
  m_xmosUtils = 0;
}


//
// Loop over all the instructions and formats and create a class definition
// for each
//
void InstructionClassGenerator::generateDefinitions()
{
  int numInstructions = m_dbInterface.numInstructions();

  for (int instNum = 0; instNum < numInstructions; instNum++)
  {
    const DbInstruction *inst = m_dbInterface.getInstruction(instNum);

    int numFormats = inst->numFormats();
    for (int fmtNum = 0; fmtNum < numFormats; fmtNum++)
    {
      const DbFormat *fmt = inst->getFormat(fmtNum);

      generateClassDefStart(inst, fmt);
      generateGetOperandFieldMethod(inst, fmt);
      generateGetOperandStringMethod(inst, fmt);

      generateClassDefEnd(inst, fmt);
    }
  }
}

void InstructionClassGenerator::generateClassDefStart(const DbInstruction *inst, const DbFormat *fmt)
{
  const string *instName = inst->getLowerName();
  const string *fmtName = fmt->getName();

  string fullName = *instName;
  string className = *instName + "_" + *fmtName;

  string fmtExt = "_" + *fmtName;
  fullName += " (" + *fmtName + ")";

  string isLoadStore = (inst->isLoad() || inst->isStore()) ? "true" : "false";
  string canPause = inst->canPause() ? "true" : "false";
  string isBranch = inst->isBranch() ? "true" : "false";
  string isLink = inst->isLink() ? "true" : "false";
  
  int numOperands = fmt->numOperands();
  bool usesResources = false;
  bool definesResources = false;
  for (int operNum = 0; operNum < numOperands; operNum++){
     DbOperand *oper = fmt->getOperand(operNum);
     if(oper->usesResource()){
        usesResources = true;
     }
     if(oper->definesResource()){
        definesResources = true;
     }
  }

  string usesResource = usesResources ? "true" : "false";
  string definesResource = definesResources ? "true" : "false";
  int numCycles = inst->numCycles();

  m_outFile << "class " << string(m_version) << "XtaInstruction_" << className << " extends XtaInstruction {" << endl;

  m_outFile << "    " << string(m_version) << "XtaInstruction_" << className << "(int opcode, long pc) {" << endl;
  m_outFile << "        super(\"" << fullName << "\", opcode, pc, " << 
    fmt->numBytes() << ", " << isLoadStore << ", " << canPause << ", "  << numCycles << ", " << isBranch <<", " <<  isLink <<");" << endl;
  if(inst->isLink()) {
   m_outFile << "        this.setBranchLink(true);";
  }
  m_outFile << "    }" << endl;
  m_outFile << endl;
}

void InstructionClassGenerator::generateGetOperandFieldMethod(const DbInstruction *inst, const DbFormat *fmt) 
{
  m_outFile << "    public long getOperandField(String opName) {" << endl;

  int numOperands = fmt->numOperands();
  for (int operNum = 0; operNum < numOperands; operNum++)
  {
    DbOperand *oper = fmt->getOperand(operNum);

    if (!oper->isImplied())
    {
      DbField *fld                 = oper->getField();
      const string *operName       = oper->getName();
      string       *decodeFunction = preProcess(fld->getDecode());
      m_outFile << "        if (opName.equals(\"" << *operName << "\")) {" << endl;
      m_outFile << "            return " << *decodeFunction << ";" << endl;
      m_outFile << "        }" << endl;
      SAFE_DELETE(decodeFunction);
    }
  }
  m_outFile << "        assert(false);" << endl;
  m_outFile << "        return 0;" << endl;
  m_outFile << "    }" << endl;
  m_outFile << endl;
}

void InstructionClassGenerator::generateGetOperandStringMethod(const DbInstruction *inst, const DbFormat *fmt) 
{
  m_outFile << "    public String getOperandString() {" << endl;

  const string *syntax = inst->getSyntax();
  StringVector *tokens = m_xmosUtils->stringLibrary->strTok(syntax, "", TOKENISERS);

  string fmtLine  = "";
  vector<string> mapsTo;
  vector<string> args;
  StringVector::const_iterator iter;
  for (iter = tokens->begin(); iter != tokens->end(); ++iter)
  {
    const string *token = *iter;
    DbOperand *oper = fmt->findOperand(token);

    if ((oper != NULL) && oper->isImplied())
    {
      fmtLine += *token;
    }
    else if ((oper != NULL) && oper->isImm())
    {
      fmtLine += "i 0x%x";

      string arg = "";

      // Deals with the scaling of the immediate values.
      const string *scale = oper->getScale();
      if (*scale != "0")
        arg += "(";

      // Deals with the mapping of the immediate values.
      DbResource *res = oper->getResource();
      const string *mapsToCode = res->getMapsToCode();
      if (mapsToCode != NULL)
      {
        int numRanges = res->getNumRanges();
        const string *valuesCode = res->getValuesCode();
        mapsTo.push_back("  int ranges[][] = " + *valuesCode + ";\n");
        mapsTo.push_back("  int mapsTo[][] = " + *mapsToCode + ";\n");

        char numRangesStr[32] = {0};
        sprintf(numRangesStr, "%d", numRanges);

        arg += "reverseMap(" + *oper->getField()->getDecode() + ", " + 
          numRangesStr + ", ranges, mapsTo)";
      }
      else
      {
        arg += *oper->getField()->getDecode();
      }

      if (*scale != "0")
          arg += " << " + *scale + ")";

      args.push_back(arg);
    }
    else if ((oper != NULL) && oper->isReg())
    {
      fmtLine += "r%d";
      args.push_back(*oper->getField()->getDecode());
    }
    else
    {
      fmtLine += *token;
    }
  }

  if (!args.empty())
    m_outFile << "        int opcode = getOpcode();" << endl;

  for (vector<string>::const_iterator iter = mapsTo.begin(); iter != mapsTo.end(); ++iter)
    m_outFile << "      " << *iter;

  m_outFile << "        return String.format(\"" << fmtLine;

  if (!args.empty())
  {
    uint argsIndex = 0;
    m_outFile << "\",\n";
    for (vector<string>::const_iterator iter = args.begin(); iter != args.end(); ++iter)
    {
      ++argsIndex;
      m_outFile << "            " << *iter;
      if (argsIndex == args.size())
        m_outFile << ");\n";
      else
        m_outFile << ",\n";        
    }
  }
  else
  {
    m_outFile << "\");\n";
  }
  m_outFile << "    }" << endl;
  m_outFile << endl;
}

void InstructionClassGenerator::generateClassDefEnd(const DbInstruction *inst, const DbFormat *fmt)
{
  m_outFile << "}" << endl << endl;
}

//
// Go through a string and replace keywords
//
string *InstructionClassGenerator::preProcess(const string *txt)
{
  StringVector *tokens = m_xmosUtils->stringLibrary->strTok(txt, "", XTA_TOKENISERS);
  bool skipComma = false;
  unsigned int skipTokens = 0;
  string empty = "";

  string newTxt;
  StringVector::const_iterator iter;
  for (iter = tokens->begin(); iter != tokens->end(); ++iter)
  {
    const string *token = *iter;

    // Required for token lookahead...
    const string *nextToken1 = &empty;
    const string *nextToken2 = &empty;
    if ((iter + 1) != tokens->end())
    {
      nextToken1 = *(iter + 1);
      if ((iter + 2) != tokens->end())
        nextToken2 = *(iter + 2);
    }

    if (skipTokens > 0)
    {
      --skipTokens;
      continue;
    }

    if (skipComma)
    {
      skipComma = false;
      if (*token != ",")
        newTxt = newTxt + *token;
      continue;
    }

    if (*token == "PC")
      newTxt = newTxt + "state.m_pc";
    else if (*token == "NEXT_PC")
      newTxt = newTxt + "state.m_nextPc";
    else if (*token == "EA")
      newTxt = newTxt + "state.m_ea";
    else if (*token == "DATA")
      newTxt = newTxt + "state.m_data";
    else if (*token == "STATE")
      newTxt = newTxt + "state";
    else if (*token == "PR_STATE")
      skipComma = true; // Only used for pseudo-random
    else if (*token == "RES")
      newTxt = newTxt + "state.m_res";
    else if (*token == "RES_THREAD")
      newTxt = newTxt + "state.m_resThread";
    else if (*token == "opcode")
      newTxt = newTxt + "getOpcode()";
    else if (*token == "PROCESSOR")
      newTxt = newTxt + "getProcessor()";
    else if (*token == "NULL")
      newTxt = newTxt + "null";
    else if (*token == "uint")
      newTxt = newTxt + "int";
    else if (*token == "unsigned" && *nextToken2 == "int")
    {
      newTxt = newTxt + "int";
      skipTokens = 2;
    }
    else if (*token == "-" && *nextToken1 == ">")
    {
      newTxt = newTxt + ".";
      skipTokens = 1;
    }
    else
      newTxt = newTxt + *token;

  }
  m_xmosUtils->stringLibrary->deleteStr(tokens);

  return SAFE_NEW(string(newTxt.begin(), newTxt.end()));
}
